#!/usr/bin/env node
/* =========================================================================
   build-faq-schema.mjs

   Generates FAQPage JSON-LD from the FAQ markup already in the templates,
   rather than having someone retype the questions into a second place.
   Google requires the structured data to match the visible text exactly, so
   deriving one from the other is the only way that stays true after an edit.

   Run it again after changing any FAQ copy. check-theme.mjs re-runs it and
   fails if the committed block is stale.

   Usage: node tools/build-faq-schema.mjs [--check]
   ========================================================================= */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const THEME = path.join(__dirname, '..', 'shopify-theme');
const START = '  {%- comment -%} FAQ schema: generated by tools/build-faq-schema.mjs, do not hand edit {%- endcomment -%}';
const END = '  {%- comment -%} end FAQ schema {%- endcomment -%}';

const TARGETS = ['templates/index.liquid', 'templates/page.utilities.liquid'];

/* Visible text only. Answers carry a link and some Liquid; JSON-LD is happy with
   plain text and it sidesteps every quoting problem those would create. */
const plain = (html) =>
  html
    .replace(/<[^>]+>/g, '')
    .replace(/\{\{[^}]*\}\}/g, '')
    .replace(/&amp;/g, '&')
    .replace(/&nbsp;/g, ' ')
    .replace(/&#39;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/\s+/g, ' ')
    .trim();

function extract(src) {
  const out = [];
  for (const m of src.matchAll(/<div class="faq-item">([\s\S]*?)<\/div><\/div><\/div>/g)) {
    const item = m[1];
    const q = (item.match(/class="faq-question"[^>]*>([\s\S]*?)<span class="faq-icon"/) || [])[1];
    const a = (item.match(/class="faq-answer-inner">([\s\S]*?)$/) || [])[1];
    if (q && a) out.push({ q: plain(q), a: plain(a) });
  }
  return out;
}

function block(items) {
  const json = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: items.map((x) => ({
      '@type': 'Question',
      name: x.q,
      acceptedAnswer: { '@type': 'Answer', text: x.a },
    })),
  };
  return START + '\n  <script type="application/ld+json">\n' +
    JSON.stringify(json, null, 2).split('\n').map((l) => '  ' + l).join('\n') +
    '\n  </script>\n' + END;
}

const check = process.argv.includes('--check');
let stale = 0;

for (const rel of TARGETS) {
  const file = path.join(THEME, rel);
  let src = fs.readFileSync(file, 'utf8');
  const items = extract(src);
  if (!items.length) { console.error(`${rel}: no .faq-item found`); process.exit(1); }
  const fresh = block(items);

  const s = src.indexOf(START);
  const e = src.indexOf(END);
  const current = s !== -1 && e !== -1 ? src.slice(s, e + END.length) : null;

  if (current === fresh) { console.log(`${rel}: up to date (${items.length} Q&A)`); continue; }
  stale++;
  if (check) { console.error(`${rel}: FAQ schema is STALE, run node tools/build-faq-schema.mjs`); continue; }

  if (current !== null) src = src.slice(0, s) + fresh + src.slice(e + END.length);
  else src = src.replace(/<\/section>\s*$/, '') , src = src.trimEnd() + '\n\n' + fresh + '\n';
  fs.writeFileSync(file, src);
  console.log(`${rel}: wrote FAQ schema (${items.length} Q&A)`);
  for (const i of items) console.log('    - ' + i.q);
}

if (check && stale) process.exit(1);
